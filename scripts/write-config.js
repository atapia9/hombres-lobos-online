// Writes public/config.js with the game server URL for the static client (ADR-006).
// Used by the GitHub Pages workflow:  SERVER_URL=https://… node scripts/write-config.js
// An empty SERVER_URL keeps "same origin", which only works when the server serves the page.

import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/** Returns the file content, or throws if the URL is not an https origin (or http on localhost). */
export function configSource(rawUrl) {
  const value = (rawUrl ?? '').trim();
  let origin = '';
  if (value) {
    const url = new URL(value);
    const local = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
    if (url.protocol !== 'https:' && !(url.protocol === 'http:' && local)) {
      throw new Error(`SERVER_URL must use https: "${value}"`);
    }
    origin = url.origin;
  }
  return [
    '// Server URL for the static client (ADR-006). Generated by scripts/write-config.js.',
    '// Empty means "same origin". A ?server=https://… parameter in the page URL takes precedence.',
    `export const SERVER_URL = ${JSON.stringify(origin)};`,
    '',
  ].join('\n');
}

if (import.meta.main) {
  const target = join(import.meta.dirname, '..', 'public', 'config.js');
  const source = configSource(process.env.SERVER_URL);
  await writeFile(target, source);
  console.log(`public/config.js → ${source.match(/SERVER_URL = (.*);/)[1]}`);
}
